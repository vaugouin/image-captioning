-- Contrôle du chargement du lot 2 (6 films Criterion vus sur Plex) et des jugements
-- ab-context-20261025. SELECT seulement : voie 1 (ssh vps-agent run).

SELECT VERDICT, COUNT(*) AS N, SUM(REVIEW_COMMENT IS NOT NULL) AS WITH_COMMENT
FROM T_WC_TMDB_IMAGE_CAPTION_REVIEW
WHERE EXPERIMENT = 'ab-context-20261025'
GROUP BY VERDICT ORDER BY VERDICT;

SELECT c.ID_ENTITY, m.RUNTIME, COUNT(*) AS CAPTIONS,
       SUM(c.TIMELINE_START_MIN IS NOT NULL) AS PLACED,
       SUM(c.TIMELINE_END_MIN > m.RUNTIME) AS BEYOND_RUNTIME,
       MIN(c.TIM_CREATED) AS FIRST_LOADED
FROM T_WC_TMDB_IMAGE_CAPTION c
JOIN T_WC_TMDB_MOVIE m ON m.ID_MOVIE = c.ID_ENTITY
WHERE c.TABLE_SOURCE = 'movie' AND c.ID_ENTITY IN (36872, 93, 20482, 27064, 4269, 31527)
GROUP BY c.ID_ENTITY, m.RUNTIME ORDER BY c.ID_ENTITY;

SELECT COUNT(*) AS ALL_CAPTIONS, COUNT(DISTINCT ID_ENTITY) AS FILMS
FROM T_WC_TMDB_IMAGE_CAPTION WHERE TABLE_SOURCE = 'movie';
