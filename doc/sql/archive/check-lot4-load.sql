-- Contrôle du chargement du lot 4 (tranche 4 Criterion et images manquantes des films
-- déjà traités), chargé le 2026-10-26 vers 20:07. SELECT seulement : voie 1 (ssh vps-agent run).
-- Attendu : 7 429 captions créées, 279 films, chronologie posée sur la plupart.

SELECT COUNT(*) AS CREATED, COUNT(DISTINCT ID_ENTITY) AS FILMS,
       SUM(TIMELINE_START_MIN IS NOT NULL) AS PLACED, SUM(TIMELINE_MODEL IS NULL) AS NO_TIMELINE
FROM T_WC_TMDB_IMAGE_CAPTION
WHERE TABLE_SOURCE = 'movie' AND TIM_CREATED >= '2026-10-26 20:00:00';

SELECT c.ID_ENTITY, COUNT(*) AS CAPTIONS, SUM(c.TIMELINE_START_MIN IS NOT NULL) AS PLACED,
       SUM(c.TIMELINE_END_MIN > m.RUNTIME) AS BEYOND_RUNTIME
FROM T_WC_TMDB_IMAGE_CAPTION c
JOIN T_WC_TMDB_MOVIE m ON m.ID_MOVIE = c.ID_ENTITY
WHERE c.TABLE_SOURCE = 'movie' AND c.ID_ENTITY IN (391, 539, 966, 11252, 75233, 8967, 11878, 27064)
GROUP BY c.ID_ENTITY ORDER BY c.ID_ENTITY;

SELECT CAPTION_MODEL, COUNT(*) AS ALL_CAPTIONS, COUNT(DISTINCT ID_ENTITY) AS FILMS
FROM T_WC_TMDB_IMAGE_CAPTION WHERE TABLE_SOURCE = 'movie'
GROUP BY CAPTION_MODEL;
